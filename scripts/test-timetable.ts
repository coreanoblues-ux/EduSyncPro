/**
 * 수업 일정 읽기 검증. `npm run test:timetable`
 *
 * 아래 일정 문자열은 2026-08-16 운영 DB의 classes.schedule 값 전부다. 한 줄도
 * 지어내지 않았다. 시간표는 잘못 그리면 원장이 아예 안 쓰게 되는 화면이라,
 * 실제로 들어 있는 값에서만 검증한다.
 */

import { parseSchedule, parseDays, formatMinutes, DAYS } from "@shared/timetable";

let pass = 0;
let fail = 0;
function check(label: string, ok: boolean, why: string) {
  if (ok) {
    pass++;
    console.log(`✅ ${label}`);
  } else {
    fail++;
    console.log(`❌ ${label}\n   ${why}`);
  }
}

/** 읽은 결과를 "월 17:30-19:30" 꼴로 펴서 비교하기 쉽게 만든다. */
function show(schedule: string, nameHint = ""): string {
  return parseSchedule(schedule, nameHint)
    .map((s) => `${s.day} ${formatMinutes(s.startMin)}-${formatMinutes(s.endMin)}`)
    .join(", ");
}

// ─── 요일 읽기 ────────────────────────────────────────────────────────────
check("띄어 쓴 요일", parseDays("월 수 금").join("") === "월수금", parseDays("월 수 금").join(""));
check("붙여 쓴 요일", parseDays("월수").join("") === "월수", parseDays("월수").join(""));
check("요일 범위", parseDays("월~금").join("") === "월화수목금", parseDays("월~금").join(""));
check("붙임표 범위", parseDays("토-일").join("") === "토일", parseDays("토-일").join(""));
check("주말", parseDays("주말 11:00~13:00").join("") === "토일", parseDays("주말 11:00~13:00").join(""));
check(
  "'화요일'의 '일'을 일요일로 세지 않는다",
  parseDays("화요일 목요일").join("") === "화목",
  `화·목 반이 화·목·일 반으로 둔갑하면 시간표에 없는 수업이 생긴다 — ${parseDays("화요일 목요일").join("")}`
);
check(
  "요일은 늘 월요일부터 차례대로",
  parseDays("토 화 금").join("") === "화금토",
  parseDays("토 화 금").join("")
);

// ─── 오전·오후 판단 ────────────────────────────────────────────────────────
check(
  "학원 저녁 수업을 새벽으로 그리지 않는다",
  show("화 목 5:30~7:30") === "화 17:30-19:30, 목 17:30-19:30",
  `'5:30~7:30'을 곧이곧대로 새벽 5시로 그리면 시간표가 통째로 쓸모없어진다 — ${show("화 목 5:30~7:30")}`
);
check(
  "끝 시각이 뒤집히면 오후로 넘긴다",
  show("화 목 8:00~10:00") === "화 20:00-22:00, 목 20:00-22:00",
  `시작 20:00 끝 10:00이 되면 거꾸로 뒤집힌 칸이 된다 — ${show("화 목 8:00~10:00")}`
);
check(
  "6:00~10:00도 저녁 수업이다",
  show("화 목 6:00~10:00") === "화 18:00-22:00, 목 18:00-22:00",
  show("화 목 6:00~10:00")
);
check(
  "오전이라고 적혀 있으면 추측하지 않는다",
  show("오전 9:00~오전 11:00", "[정]주말 고등부 고2 오전") === "토 09:00-11:00, 일 09:00-11:00",
  show("오전 9:00~오전 11:00", "[정]주말 고등부 고2 오전")
);
check(
  "24시간 표기는 그대로 둔다",
  show("월수 19:00-21:00") === "월 19:00-21:00, 수 19:00-21:00",
  show("월수 19:00-21:00")
);
check(
  "오후 1시 이후 표기도 그대로",
  show("토-일 14:30-16:30") === "토 14:30-16:30, 일 14:30-16:30",
  show("토-일 14:30-16:30")
);
check(
  "9~12시는 오전으로 둔다",
  show("주말 11:00~13:00") === "토 11:00-13:00, 일 11:00-13:00",
  `주말 오전 수업이 실제로 있어서 오후로 밀면 안 된다 — ${show("주말 11:00~13:00")}`
);
check(
  "추측한 시각은 표시가 남는다",
  parseSchedule("화 목 5:30~7:30")[0].guessedMeridiem === true &&
    parseSchedule("월수 19:00-21:00")[0].guessedMeridiem === false,
  "코드가 정한 시각인지 원장이 적은 시각인지 화면에서 구분할 수 있어야 한다"
);

// ─── 한국식 시각 ──────────────────────────────────────────────────────────
check("'6시~8시'", show("화 목 6시~8시") === "화 18:00-20:00, 목 18:00-20:00", show("화 목 6시~8시"));
check("'8시~10시'", show("화 목 8시~10시") === "화 20:00-22:00, 목 20:00-22:00", show("화 목 8시~10시"));
check(
  "'7시 ~ 8시 30분'",
  show("월 수 금 7시 ~ 8시 30분") === "월 19:00-20:30, 수 19:00-20:30, 금 19:00-20:30",
  show("월 수 금 7시 ~ 8시 30분")
);
check(
  "'5시 ~ 6시30분'",
  show("토일 5시 ~ 6시30분") === "토 17:00-18:30, 일 17:00-18:30",
  show("토일 5시 ~ 6시30분")
);

// ─── 여러 덩어리 ──────────────────────────────────────────────────────────
check(
  "요일-시간 묶음이 둘이면 둘 다 올린다",
  show("월 수 [5:30~7:30], 금 [7:00~8:30]") ===
    "월 17:30-19:30, 수 17:30-19:30, 금 19:00-20:30",
  `금요일 수업이 통째로 빠지면 시간표를 믿을 수 없다 — ${show("월 수 [5:30~7:30], 금 [7:00~8:30]")}`
);
check(
  "요일이 다른 두 묶음",
  show("화 목 8:00~10:00, 토 11:30~13:00") ===
    "화 20:00-22:00, 목 20:00-22:00, 토 11:30-13:00",
  show("화 목 8:00~10:00, 토 11:30~13:00")
);
check(
  "대괄호 안의 시각도 읽는다",
  show("월 수 [7:00~9:00], 금 [7:00~8:30]") ===
    "월 19:00-21:00, 수 19:00-21:00, 금 19:00-20:30",
  show("월 수 [7:00~9:00], 금 [7:00~8:30]")
);
check(
  "월 수 금 6:30-8:20",
  show("월 수 금 6:30-8:20") === "월 18:30-20:20, 수 18:30-20:20, 금 18:30-20:20",
  show("월 수 금 6:30-8:20")
);

// ─── 못 읽는 값은 격자에 올리지 않는다 ──────────────────────────────────────
check(
  "시각이 없으면 올리지 않는다",
  show("월~금") === "" && show("토-일") === "",
  `'월~금'은 요일뿐이라 몇 시에 그릴지 알 수 없다 — ${show("월~금")}`
);
check(
  "끝 시각이 없으면 올리지 않는다",
  show("토일 3시30분") === "",
  `끝 시각을 지어내면 옆 수업과 겹쳐 보인다 — ${show("토일 3시30분")}`
);
check(
  "요일도 시각도 없으면 올리지 않는다",
  show("") === "" && show("추후 공지") === "",
  show("추후 공지")
);
check(
  "요일이 없으면 반 이름에서 빌려온다",
  show("13:00~15:00", "[정]주말 고1 오후") === "토 13:00-15:00, 일 13:00-15:00",
  `일정 칸에 시각만 있는 반이 실제로 있다. 이름의 '주말'을 읽어야 격자에 올라간다 — ${show("13:00~15:00", "[정]주말 고1 오후")}`
);
check(
  "이름에도 요일이 없으면 올리지 않는다",
  show("13:00~15:00", "고급반") === "",
  "요일을 모르면 아무 칸에나 그리는 대신 따로 모아 보여줘야 한다"
);

// ─── 운영 DB 전체를 한 번에 ────────────────────────────────────────────────
const real: Array<[string, string]> = [
  ["월 수 [5:30~7:30], 금 [7:00~8:30]", "[정]월 수 심화A"],
  ["월 수 [7:00~9:00], 금 [7:00~8:30]", "[정]월 수 심화 B"],
  ["오전 9:00~오전 11:00", "[정]주말 고등부 고2 오전 "],
  ["13:00~15:00", "[정]주말 고1 오후"],
  ["월~금", "[국어-이]주중-중등반"],
  ["월~금", "[국어-이]주중-고등반"],
  ["월~금", "[국어-이]주중-초등반"],
  ["토-일", "[국어-이]주말-고등반"],
  ["토-일 14:30-16:30", "[정]주말 고3 오후"],
  ["화 목 5:30~7:30", "[정]화 목 심화 A-F"],
  ["화 목 8:00~10:00, 토 11:30~13:00", "[정]화 목 심화 C"],
  ["월 수 금 6:30-8:20", "[란]중1 기본 - 월수금"],
  ["화 목 7:00-9:00", "[정]화목 - 기본심화 B"],
  ["화 목 6:40-9:00", "[란]화 목 중1 기본"],
  ["주말 11:00~13:00", "[정]주말 고1 오전"],
  ["화 목 6:00~10:00", "김명근 중등영어"],
  ["토-일", "김명근 고등영어"],
  ["월수 19:00-21:00", "중1 심화반 [월수B]"],
  ["화 목 6시~8시", "화 목 A"],
  ["화 목 8시~10시", "화 목 B"],
  ["월 수 금 7시 ~ 8시 30분", "월 수 금 A"],
  ["토일 3시30분", "삼육중B"],
  ["토일 5시 ~ 6시30분", "삼육중A반"],
];

const placed = real.filter(([s, n]) => parseSchedule(s, n).length > 0);
const unplaced = real.filter(([s, n]) => parseSchedule(s, n).length === 0);

check(
  "운영 데이터 23개 중 17개가 격자에 올라간다",
  placed.length === 17,
  `${placed.length}개만 올라간다`
);
check(
  "못 올리는 6개는 정말로 시각을 알 수 없는 값이다",
  unplaced.map(([s]) => s).join(" | ") === "월~금 | 월~금 | 월~금 | 토-일 | 토-일 | 토일 3시30분",
  `요일만 적힌 값과 끝 시각이 없는 값뿐이어야 한다. 읽을 수 있는데 놓친 게 섞이면 ` +
    `그 수업이 시간표에서 사라진다 — ${unplaced.map(([s, n]) => `"${s}"(${n})`).join(", ")}`
);
check(
  "모든 칸의 끝이 시작보다 뒤에 있다",
  real.every(([s, n]) => parseSchedule(s, n).every((x) => x.endMin > x.startMin)),
  "거꾸로 뒤집힌 칸은 격자에서 높이가 음수가 되어 화면이 깨진다"
);
check(
  "모든 칸이 하루 안에 들어온다",
  real.every(([s, n]) =>
    parseSchedule(s, n).every((x) => x.startMin >= 0 && x.endMin <= 24 * 60)
  ),
  "자정을 넘는 칸이 생기면 격자 밖으로 삐져나간다"
);
check(
  "모든 칸의 요일이 월~일 중 하나다",
  real.every(([s, n]) => parseSchedule(s, n).every((x) => DAYS.includes(x.day))),
  "격자에 없는 요일이 나오면 그 수업은 화면에서 사라진다"
);

console.log("\n── 운영 데이터 읽은 결과 ──");
for (const [s, n] of real) {
  const got = show(s, n);
  console.log(`  ${n.padEnd(24)} "${s}"\n    → ${got || "(격자에 올리지 않음)"}`);
}

console.log(`\n${pass}건 통과 / ${fail}건 실패`);
process.exit(fail === 0 ? 0 : 1);
