/**
 * 오래된 학부모 링크 토큰을 지우는 장치 (파기).
 *
 * ════════════════════════════════════════════════════════════════════════
 * 만료와 파기는 다르다
 * ════════════════════════════════════════════════════════════════════════
 *   · **만료 (5일)** — 학부모가 눌러도 안 열린다. shareState 가 "expired" 를
 *     돌려주고 안내 화면이 뜬다. 토큰 값은 DB 에 남아 있다.
 *   · **파기 (6개월)** — 토큰 값 자체를 NULL 로 지운다. 이 파일이 하는 일이다.
 *
 *   학부모 입장에서는 **5일 뒤에 이미 못 본다.** 파기는 "쓸모없어진 주소를
 *   DB 에 쌓아 두지 않는다" 는 추가 조치다. 보안이 극적으로 좋아지는 것은
 *   아니지만(만료가 이미 막고 있다), 지금 DB 가 유출될 경우의 노출을 줄인다.
 *
 * ════════════════════════════════════════════════════════════════════════
 * 왜 이 파일이 shareLink.ts 와 따로 있는가
 * ════════════════════════════════════════════════════════════════════════
 *   shareLink.ts 는 DB 를 모른다(crypto 와 타입만 쓴다). 그래서 테스트가
 *   DB 없이 그 파일을 불러 검사할 수 있다. 여기에 storage 를 끌어들이면
 *   테스트가 DB 접속을 시도하다 죽는다. 그 경계를 지키려고 파일을 나눴다.
 *
 * ════════════════════════════════════════════════════════════════════════
 * ⚠️ 스스로 자료를 지우는 장치다 — 안전장치를 확인하고 고칠 것
 * ════════════════════════════════════════════════════════════════════════
 *   실제 삭제는 storage.purgeExpiredShareTokens 한 곳에서만 일어나고,
 *   그 함수는
 *     · UPDATE 다 (db.delete 를 쓰지 않는다 — 행이 사라지는 일은 없다)
 *     · share_token 한 칸만 NULL 로 만든다
 *     · 점수·이름·메모·발급일·열어 본 횟수는 건드리지 않는다
 *     · 발급일이 적혀 있지 않으면 건너뛴다 ("모르겠으면 지우지 않는다")
 *   로 되어 있다. 테스트가 이 네 가지를 글자로 확인한다: npm run test:share
 *
 *   지운 뒤 그 기록은 "링크 없음" 상태가 되어, 원장 화면에 다시
 *   `학부모 링크 만들기` 버튼이 보인다. 누르면 새 토큰이 나온다 —
 *   기능이 사라지는 것이 아니다.
 */

import { storage } from "../storage";
import { sharePurgeCutoff, SHARE_PURGE_DAYS } from "./shareLink";

/** 한 번 돌린다. 지운 건수를 돌려준다(로그·테스트용). */
export async function runSharePurge(now: Date = new Date()): Promise<number> {
  const cutoff = sharePurgeCutoff(now);
  const cleared = await storage.purgeExpiredShareTokens(cutoff);
  if (cleared > 0) {
    // 토큰 값은 절대 찍지 않는다. 건수만 남긴다.
    console.log(
      `🧹 오래된 학부모 링크 주소 ${cleared}건을 지웠습니다 ` +
        `(발급 후 ${SHARE_PURGE_DAYS}일 경과). 점수 기록은 그대로입니다.`
    );
  }
  return cleared;
}

/**
 * 6시간마다 돌린다. 학년 자동승급·놓친 자리 찾기와 같은 방식이다.
 *
 * 기준이 6개월이라 6시간 간격은 넉넉하다. 간격을 짧게 잡은 이유는 정확도가
 * 아니라 **다른 두 장치와 모양을 똑같이 두려는 것** 이다. 자동으로 도는
 * 코드가 서로 다른 규칙으로 돌면 나중에 읽는 사람이 헷갈린다.
 *
 * 거의 모든 호출은 0건을 지우고 끝난다(조건에 맞는 행이 없다). 조건이
 * share_token IS NOT NULL 로 시작하므로, 토큰이 달린 행에만 만들어 둔
 * 부분 인덱스를 타고 바로 끝난다.
 */
export function startSharePurgeScheduler() {
  const tick = () => {
    runSharePurge().catch((err) => {
      // 실패해도 서버는 계속 돈다. 이 장치가 멈춰서 생기는 손해는
      // "죽은 주소가 DB 에 더 오래 남는다" 뿐이다 — 학부모는 이미 못 본다.
      console.error("❌ 오래된 학부모 링크 주소 정리 실패:", err);
    });
  };
  tick();
  setInterval(tick, 6 * 60 * 60 * 1000);
}
